let lang = "id";
try { lang = localStorage.getItem("lang") === "en" ? "en" : "id"; } catch {}
document.documentElement.lang = lang;

export const getLang = () => lang;
export const locale = () => (lang === "en" ? "en-US" : "id-ID");

export function setLang(next) {
  lang = next === "en" ? "en" : "id";
  document.documentElement.lang = lang;
  try { localStorage.setItem("lang", lang); } catch {}
}

export function t(key, vars = {}) {
  const s = DICT[lang][key] ?? DICT.id[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? `{${k}}`);
}

// label statis di index.html: data-i18n (textContent) / data-i18n-title (title + aria-label)
export function applyStatic(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute("aria-label", el.title);
  });
}
